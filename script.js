const API_URL = "http://127.0.0.1:8000";

// Global 3D viewer
let molecularViewer = null;

// HIGHLIGHT SELECTED CARBON ATOMS
function applyMoleculeStyles(highlightedAtomIndices = []) {

    if (!molecularViewer) {
        return;
    }

    // Default appearance
    molecularViewer.setStyle({}, {
        stick: { radius: 0.2 },
        sphere: { scale: 0.35 }
    });

    // Carbon
    molecularViewer.setStyle({ elem: "C" }, {
        stick: { color: "#424242" },
        sphere: { color: "#424242", scale: 0.35 }
    });

    // Hydrogen
    molecularViewer.setStyle({ elem: "H" }, {
        stick: { color: "#BDBDBD" },
        sphere: { color: "#BDBDBD", scale: 0.35 }
    });

    // Oxygen
    molecularViewer.setStyle({ elem: "O" }, {
        stick: { color: "#E53935" },
        sphere: { color: "#E53935", scale: 0.35 }
    });

    // Nitrogen
    molecularViewer.setStyle({ elem: "N" }, {
        stick: { color: "#1E88E5" },
        sphere: { color: "#1E88E5", scale: 0.35 }
    });

    // Highlight selected carbon atoms in yellow
    highlightedAtomIndices.forEach(index => {

        molecularViewer.setStyle(
            { index: Number(index) },
            {
                stick: {
                    color: "#FFD600",
                    radius: 0.3
                },
                sphere: {
                    color: "#FFD600",
                    scale: 0.35
                }
            }
        );

    });

    molecularViewer.render();
}

// GENERATE 2D MOLECULE

async function draw2D() {

    const smiles = document.getElementById("smiles").value.trim();
    const status = document.getElementById("status");

    try {

        status.textContent = "Generating 2D structure...";

        const response = await fetch(`${API_URL}/generate-2d`, {
            method: "POST",
            headers: {
                "Content-Type": "application/json"
            },
            body: JSON.stringify({ smiles: smiles })
        });

        if (!response.ok) {
            throw new Error(await response.text());
        }

        const data = await response.json();

        document.getElementById("molecule2D").innerHTML = data.svg;
        
        const atomClasses = [
        ...document.querySelectorAll("#molecule2D svg [class]")
    ]
        .map(element => element.getAttribute("class"))
        .filter(className => className.includes("atom-"));

        console.log("RDKit SVG atom classes:", atomClasses);

        console.log("Atom details:", data.atoms);

        status.textContent = "2D molecule generated successfully.";

    } catch (error) {

        status.textContent = "2D Error: " + error.message;

        console.error(error);
    }
}

// GENERATE 3D MOLECULE

async function show3D() {

    const smiles = document.getElementById("smiles").value.trim();
    const status = document.getElementById("status");

    try {

        status.textContent = "Generating 3D structure...";

        const response = await fetch(`${API_URL}/generate-3d`, {
            method: "POST",
            headers: {
                "Content-Type": "application/json"
            },
            body: JSON.stringify({ smiles: smiles })
        });

        if (!response.ok) {
            throw new Error(await response.text());
        }

        const data = await response.json();

        // Convert coordinates into XYZ format
        let xyz = data.atoms.length + "\n";
        xyz += "Generated by RDKit\n";

        data.atoms.forEach(atom => {
            xyz += `${atom.element} ${atom.x} ${atom.y} ${atom.z}\n`;
        });

        if (typeof $3Dmol === "undefined") {
            throw new Error("3Dmol.js library did not load.");
        }

        // Create or reuse viewer
        if (molecularViewer === null) {

            molecularViewer = $3Dmol.createViewer("viewer", {
                backgroundColor: "white"
            });

        } else {

            molecularViewer.clear();
        }

        molecularViewer.addModel(xyz, "xyz");

        // Apply default molecular
        applyMoleculeStyles();
     
        // HIGHLIGHT SELECTED ATOMS IN 2D
        
        function highlight2DAtoms(atomIndices = []) {

        const svg = document.querySelector("#molecule2D svg");

        if (!svg) {
        console.log("Generate the 2D structure first.");
        return;
    }

        // Remove previous highlighting
        svg.querySelectorAll(".nmr-highlight").forEach(element => {
        element.classList.remove("nmr-highlight");
    });

        // Highlight elements associated with selected atoms
        atomIndices.forEach(index => {

        const className = `atom-${Number(index)}`;

        svg.querySelectorAll("*").forEach(element => {

            if (element.classList.contains(className)) {
                element.classList.add("nmr-highlight");
            }

        });

    });
}
        molecularViewer.zoomTo();
        molecularViewer.render();

        // Carbon
        molecularViewer.setStyle(
            { elem: "C" },
            {
                stick: { color: "#424242" },
                sphere: { color: "#424242", scale: 0.35 }
            }
        );

        // Hydrogen
        molecularViewer.setStyle(
            { elem: "H" },
            {
                stick: { color: "#BDBDBD" },
                sphere: { color: "#BDBDBD", scale: 0.35 }
            }
        );

        // Oxygen
        molecularViewer.setStyle(
            { elem: "O" },
            {
                stick: { color: "#E53935" },
                sphere: { color: "#E53935", scale: 0.35 }
            }
        );

        // Nitrogen
        molecularViewer.setStyle(
            { elem: "N" },
            {
                stick: { color: "#1E88E5" },
                sphere: { color: "#1E88E5", scale: 0.35 }
            }
        );

        molecularViewer.zoomTo();
        molecularViewer.render();

        status.textContent =
            "3D molecule generated successfully. Atoms: " +
            data.total_atoms;

    } catch (error) {

        status.textContent = "3D Error: " + error.message;

        console.error(error);
    }
}

// GENERATE 13C NMR SPECTRUM

async function loadNMRSpectrum() {

    const smiles = document.getElementById("smiles").value.trim();

    const status = document.getElementById("status");
    const peakInfo = document.getElementById("peakInfo");

    try {

        status.textContent = "Generating NMR spectrum...";

        peakInfo.textContent = "Loading spectrum...";

        const response = await fetch(
            `${API_URL}/nmr-spectrum-by-smiles`,
            {
                method: "POST",
                headers: {
                    "Content-Type": "application/json"
                },
                body: JSON.stringify({ smiles: smiles })
            }
        );

        if (!response.ok) {
            throw new Error(await response.text());
        }

        const data = await response.json();
        
        const shifts = data.spectrum.map(
            peak => peak.chemical_shift_ppm
        );

        const intensities = data.spectrum.map(
            peak => peak.intensity
        );

        // Vertical peak lines
        const lineX = [];
        const lineY = [];

        data.spectrum.forEach(peak => {

            lineX.push(
                peak.chemical_shift_ppm,
                peak.chemical_shift_ppm,
                null
            );

            lineY.push(
                0,
                peak.intensity,
                null
            );

        });

        const peakLines = {
            x: lineX,
            y: lineY,
            type: "scatter",
            mode: "lines",
            line: {
                width: 2
            },
            hoverinfo: "skip",
            showlegend: false
        };

        // Clickable peak markers
        const peakMarkers = {
            x: shifts,
            y: intensities,
            type: "scatter",
            mode: "markers",
            marker: {
                size: 11
            },
            customdata: data.spectrum.map(
                peak => peak.atoms
            ),
            hovertemplate:
                "Shift: %{x} ppm<br>" +
                "Intensity: %{y}<br>" +
                "Click to identify carbon<extra></extra>",
            name: "Carbon peaks"
        };

        const layout = {

            title: "13C NMR Spectrum",

            xaxis: {
                title: "Chemical Shift (ppm)",
                autorange: false,
                range: [220, 0]
            },

            yaxis: {
                title: "Relative Intensity",
                rangemode: "tozero"
            },

            showlegend: false,

            margin: {
                l: 60,
                r: 30,
                t: 60,
                b: 60
            }
        };

        const config = {
            responsive: true
        };

        await Plotly.newPlot(
            "nmrSpectrum",
            [peakLines, peakMarkers],
            layout,
            config
        );
    
// HANDLE NMR PEAK CLICKS

const spectrumElement =
    document.getElementById("nmrSpectrum");

spectrumElement.on("plotly_click", function(event) {

    const point = event.points[0];

    if (point.curveNumber !== 1) {
        return;
    }

    const atoms = point.customdata;

    const atomIndices = atoms.map(
        atom => Number(atom.atom_index)
    );

    const atomNames = atomIndices.map(
        index => `Carbon atom ${index}`
    );

    peakInfo.textContent =
        `Chemical shift: ${point.x} ppm | ` +
        `Atoms: ${atomNames.join(", ")}`;

    // Highlight selected atoms in 3D
    if (molecularViewer) {

        applyMoleculeStyles(atomIndices);

        peakInfo.textContent += " | Highlighted in 3D";

    } else {

        peakInfo.textContent +=
            " | Generate the 3D structure to see highlighting.";

    }

    console.log("Selected peak:", point.x);
    console.log("Highlighted atom indices:", atomIndices);

});

        status.textContent =
            "NMR spectrum generated successfully. Peaks: " +
            data.total_peaks;

        peakInfo.textContent =
            "Click a peak to identify its carbon atom.";

    } catch (error) {

        status.textContent =
            "NMR Error: " + error.message;

        peakInfo.textContent = "Spectrum unavailable.";

        console.error(error);
    }
}
async function predictNMR() {

    const smiles = document.getElementById("smiles").value.trim();
    const resultsDiv = document.getElementById("predictionResults");

    try {
        resultsDiv.textContent = "Predicting chemical shifts...";

        const response = await fetch(`${API_URL}/predict-nmr`, {
            method: "POST",
            headers: {
                "Content-Type": "application/json"
            },
            body: JSON.stringify({ smiles: smiles })
        });

        const data = await response.json();

        if (!response.ok) {
            throw new Error(data.detail || "Prediction failed");
        }

        resultsDiv.innerHTML = `
            <h3>Prediction Results</h3>
            <p>Total carbon atoms: ${data.total_carbon_atoms}</p>
            <table border="1" cellpadding="8">
                <tr>
                    <th>Atom Index</th>
                    <th>Element</th>
                    <th>Predicted Shift (ppm)</th>
                </tr>
                ${data.predictions.map(item => `
                    <tr>
                        <td>${item.atom_index}</td>
                        <td>${item.element}</td>
                        <td>${item.predicted_shift_ppm}</td>
                    </tr>
                `).join("")}
            </table>
            <p><small>Experimental validation has not been performed.</small></p>
        `;

    } catch (error) {
        resultsDiv.textContent = "Error: " + error.message;
    }
}